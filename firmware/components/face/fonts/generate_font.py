#!/usr/bin/env python3
"""Regenerate the static LVGL font from the LVGL-bundled OFL source font.

Requires lv_font_conv 1.5.3. Bitmap bytes are embedded separately so firmware
uses flash directly, without loading a multi-megabyte font into runtime RAM.
"""
import argparse
import re
import subprocess
import tempfile
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--converter", default="lv_font_conv")
    parser.add_argument("--font", type=Path, required=True)
    args = parser.parse_args()
    out_dir = Path(__file__).resolve().parent
    ranges = ("0x20-0x7E,0xA0-0xFF,0x2000-0x206F,0x3000-0x3029,"
              "0x3038-0x303F,0x4E00-0x9FFF,0xFF00-0xFFEF")
    with tempfile.TemporaryDirectory(prefix="xiaodai-font-") as tmp:
        source = Path(tmp) / "xiaodai_font_sc_16.c"
        subprocess.run([args.converter, "--size", "16", "--bpp", "4", "--font", str(args.font),
                        "--range", ranges, "--no-compress", "--no-prefilter", "--no-kerning",
                        "--format", "lvgl", "--lv-include", "lvgl.h", "--lv-font-name",
                        "xiaodai_font_sc_16", "-o", str(source)], check=True)
        text = source.read_text(encoding="utf-8")
        pattern = r"static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap\[\] = \{(.*?)\n\};"
        match = re.search(pattern, text, re.DOTALL)
        if not match:
            raise ValueError("Unrecognized converter output; refusing to emit font")
        bitmap = bytes(int(byte, 16) for byte in re.findall(r"0x([0-9a-fA-F]{1,2})\b", match.group(1)))
        if len(bitmap) < 1_000_000:
            raise ValueError("Unexpectedly small glyph bitmap")
        replacement = ("/* Glyph data is embedded in flash by ESP-IDF; see generate_font.py. */\n"
                       "extern const uint8_t _binary_xiaodai_glyph_bitmap_bin_start[];")
        text = text[:match.start()] + replacement + text[match.end():]
        if text.count(".glyph_bitmap = glyph_bitmap,") != 1:
            raise ValueError("Unrecognized font descriptor; refusing to emit font")
        text = text.replace(".glyph_bitmap = glyph_bitmap,",
                            ".glyph_bitmap = _binary_xiaodai_glyph_bitmap_bin_start,")
        text = re.sub(r" \* Opts: .*", " * Generated by fonts/generate_font.py; source: Source Han Sans SC, OFL 1.1", text, count=1)
        (out_dir / "xiaodai_glyph_bitmap.bin").write_bytes(bitmap)
        (out_dir / "xiaodai_font_sc_16.c").write_text(text, encoding="utf-8")
        print(f"Wrote {len(bitmap)} bitmap bytes and LVGL descriptors")


if __name__ == "__main__":
    main()
