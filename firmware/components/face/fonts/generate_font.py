#!/usr/bin/env python3
"""Generate the OFL Source Han fonts used by the device with LVGL's lv_font_conv."""
import argparse
import re
import subprocess
import tempfile
from pathlib import Path


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--converter", default="lv_font_conv")
    parser.add_argument("--font", type=Path, required=True)
    args = parser.parse_args()
    out = Path(__file__).resolve().parent
    ranges = ("0x20-0x7E,0xA0-0xFF,0x2000-0x206F,0x3000-0x3029,"
              "0x3038-0x303F,0x4E00-0x9FFF,0xFF00-0xFFEF")
    # Settings uses fixed strings plus the generated theme and expression names.
    settings_sources = [out.parent / "face_settings.c", *sorted((out.parent / "include").glob("*_generated.h"))]
    symbols = "".join(sorted({ch for path in settings_sources for ch in path.read_text()
                              if 0x3000 <= ord(ch) <= 0xFFEF}))
    with tempfile.TemporaryDirectory(prefix="xiaodai-font-") as tmp:
        for size, bpp, charset in [(30, 2, ["--range", ranges]),
                                   (22, 4, ["--range", "0x20-0x7E,0xA0-0xFF", "--symbols", symbols])]:
            name = f"xiaodai_font_sc_{size}"
            path = Path(tmp) / f"{name}.c"
            subprocess.run([args.converter, "--size", str(size), "--bpp", str(bpp), "--font", str(args.font),
                            *charset, "--no-kerning", "--format", "lvgl", "--lv-include", "lvgl.h",
                            "--lv-font-name", name, "-o", str(path)], check=True)
            text = path.read_text()
            text = re.sub(r" \* Opts: .*", " * Generated by fonts/generate_font.py; Source Han Sans SC, OFL 1.1",
                          text, count=1)
            if size == 30:
                # Embed the compressed bitmap as mapped rodata; LVGL decodes the requested glyph.
                pattern = r"static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap\[\] = \{(.*?)\n\};"
                match = re.search(pattern, text, re.DOTALL)
                if not match or text.count(".glyph_bitmap = glyph_bitmap,") != 1:
                    raise ValueError("Unrecognized LVGL font descriptor")
                bitmap = bytes(int(b, 16) for b in re.findall(r"0x([0-9a-fA-F]{1,2})\b", match[1]))
                if len(bitmap) < 1_000_000:
                    raise ValueError("Incomplete Chinese font")
                (out / "xiaodai_glyph_bitmap.bin").write_bytes(bitmap)
                symbol = "_binary_xiaodai_glyph_bitmap_bin_start"
                text = text[:match.start()] + f"extern const uint8_t {symbol}[];" + text[match.end():]
                text = text.replace(".glyph_bitmap = glyph_bitmap,", f".glyph_bitmap = {symbol},")
            (out / f"{name}.c").write_text(text.rstrip("\n") + "\n")


if __name__ == "__main__":
    main()
