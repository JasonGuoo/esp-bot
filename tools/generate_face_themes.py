#!/usr/bin/env python3
"""Generate firmware face palette header from shared/themes.json. No dependencies."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "shared" / "themes.json"
TARGET = ROOT / "firmware" / "components" / "face" / "include" / "face_themes_generated.h"
FIELDS = ("background", "eye", "pupil", "subtitle_bg", "subtitle_text", "chrome", "chrome_text")


def generate(data: dict) -> str:
    themes = data["themes"]
    if data.get("schema_version") != 1 or not themes:
        raise ValueError("Unsupported or empty theme schema")
    seen = set()
    lines = [
        "// Generated by tools/generate_face_themes.py; DO NOT EDIT.",
        "// Single source of truth: shared/themes.json",
        "#pragma once",
        "#include <stdint.h>",
        "typedef struct {",
        "    const char *id;",
        "    const char *name;",
    ]
    lines += [f"    uint32_t {field};" for field in FIELDS]
    lines += ["} face_theme_palette_t;", "static const face_theme_palette_t k_face_palettes[] = {"]
    for theme in themes:
        tid = theme["id"]
        if not re.fullmatch(r"[a-z][a-z0-9_-]*", tid) or tid in seen:
            raise ValueError(f"Invalid or duplicate theme ID: {tid}")
        seen.add(tid)
        if not re.fullmatch(r"[A-Za-z0-9 -]+", theme["name"]):
            raise ValueError("Theme name must be ASCII for the default LVGL font")
        rgb = []
        for field in FIELDS:
            value = theme[field]
            if not re.fullmatch(r"#[0-9A-Fa-f]{6}", value):
                raise ValueError(f"Invalid hex in {tid}.{field}")
            rgb.append("0x" + value[1:].upper())
        lines.append(f'    {{"{tid}", "{theme["name"]}", ' + ", ".join(rgb) + "},")
    lines += [
        "};",
        "#define FACE_THEME_COUNT (sizeof(k_face_palettes) / sizeof(k_face_palettes[0]))",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail if generated header is stale")
    args = parser.parse_args()
    content = generate(json.loads(SOURCE.read_text(encoding="utf-8")))
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
            raise SystemExit("Generated header is stale: run python3 tools/generate_face_themes.py")
        print("Palette header matches shared/themes.json")
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(content, encoding="utf-8")
        print(f"Wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
