#!/usr/bin/env python3
"""Compile appearance-pack manifests into a small firmware const table."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "shared" / "themes.json"
TARGET = ROOT / "firmware" / "components" / "face" / "include" / "face_themes_generated.h"
EXPRESSIONS_SOURCE = ROOT / "shared" / "eve-expressions.json"
EXPRESSIONS_TARGET = TARGET.with_name("face_expressions_generated.h")
PREVIEW_TARGET = ROOT / "preview" / "eve-expressions.generated.js"
RUST_TARGET = ROOT / "server/bot-server/src-tauri/src/face_catalog_generated.rs"
SERVER_TS_TARGET = ROOT / "server/bot-server/src/face-catalog.generated.ts"
FIELDS = ("background", "eye", "pupil", "subtitle_bg", "subtitle_text", "chrome", "chrome_text")
RENDERERS = ("outline", "pill", "eve")  # must correspond to compiled face_renderer drivers


def generate(data: dict) -> str:
    themes = data["themes"]
    if data.get("schema_version") != 1 or not themes:
        raise ValueError("Unsupported or empty theme schema")
    seen = set()
    lines = [
        "// Generated by tools/generate_face_themes.py; DO NOT EDIT.",
        "// Appearance manifest: shared/themes.json. Extend with new renderer modules.",
        "#pragma once",
        "#include <stdint.h>",
        "typedef struct {",
        "    const char *id;",
        "    const char *name;",
        "    const char *name_zh;",
        "    const char *renderer_id;",
    ]
    lines += [f"    uint32_t {field};" for field in FIELDS]
    lines += [
        "    uint16_t blink_interval_ms;",
        "    uint16_t blink_duration_ms;",
        "    uint8_t gaze_smoothing;",
        "} face_theme_t;",
        "static const face_theme_t k_face_themes[] = {",
    ]
    for theme in themes:
        tid = theme["id"]
        if not re.fullmatch(r"[a-z][a-z0-9_-]*", tid) or tid in seen:
            raise ValueError(f"Invalid or duplicate theme ID: {tid}")
        seen.add(tid)
        if not re.fullmatch(r"[A-Za-z0-9 -]+", theme["name"]):
            raise ValueError("English name must be ASCII")
        if not isinstance(theme.get("name_zh"), str) or not theme["name_zh"]:
            raise ValueError(f"Missing localized name: {tid}")
        renderer = theme.get("renderer")
        if renderer not in RENDERERS:
            raise ValueError(f"Unregistered renderer: {renderer}")
        colors = []
        for field in FIELDS:
            value = theme[field]
            if not re.fullmatch(r"#[0-9A-Fa-f]{6}", value):
                raise ValueError(f"Invalid hex in {tid}.{field}")
            colors.append("0x" + value[1:].upper())
        motion = theme.get("motion", {})
        if not isinstance(motion, dict):
            raise ValueError(f"Invalid motion object in {tid}")
        blink_interval = motion.get("blink_interval_ms", 3600)
        blink_duration = motion.get("blink_duration_ms", 130)
        easing = motion.get("gaze_smoothing", 4)
        for label, number, low, high in (
            ("blink_interval_ms", blink_interval, 500, 60000),
            ("blink_duration_ms", blink_duration, 70, 2000),
            ("gaze_smoothing", easing, 1, 20),
        ):
            if isinstance(number, bool) or not isinstance(number, int) or not low <= number <= high:
                raise ValueError(f"{tid}.{label} must be integer {low}..{high}")
        strings = ", ".join(json.dumps(theme[key], ensure_ascii=False) for key in (
            "id", "name", "name_zh", "renderer"))
        values = ", ".join(colors + list(map(str, (blink_interval, blink_duration, easing))))
        lines.append(f"    {{{strings}, {values}}},")
    default_id = data.get("default_theme")
    if default_id not in seen:
        raise ValueError("default_theme must name an installed theme")
    lines += [
        "};",
        "#define FACE_THEME_COUNT (sizeof(k_face_themes) / sizeof(k_face_themes[0]))",
        f"#define FACE_DEFAULT_THEME_INDEX {next(i for i, t in enumerate(themes) if t['id'] == default_id)}",
        "",
    ]
    return "\n".join(lines)


def generate_expressions(data: dict) -> tuple[str, str]:
    """Keep native silhouettes, expression IDs and browser previews identical."""
    if data.get("schema_version") != 1:
        raise ValueError("Unsupported expression schema")
    shapes = data["shapes"]
    expressions = data["expressions"]
    ids = [e["id"] for e in expressions]
    if not ids or len(set(ids)) != len(ids):
        raise ValueError("Empty or duplicate expression IDs")
    for name, points in shapes.items():
        if len(points) != 26 or any(type(p) is not int or not -50 <= p <= 150 for p in points):
            raise ValueError(f"{name}: expected one move + four bounded cubic curves")
        if points[:2] != points[-2:]:
            raise ValueError(f"{name}: silhouette must close")
    for e in expressions:
        if not re.fullmatch(r"[a-z][a-z0-9_]{0,14}", e["id"]) or not e.get("name_zh"):
            raise ValueError("Invalid expression ID or label")
        if len(e["eyes"]) != 2 or any(s not in shapes for s in e["eyes"]):
            raise ValueError(f"Missing eye shapes for {e['id']}")
    order = data["preview_order"]
    if not order or len(set(order)) != len(order) or any(e not in ids for e in order):
        raise ValueError("Preview expressions must be nonempty, unique and known")
    lines = [
        "// Generated by tools/generate_face_themes.py; DO NOT EDIT.",
        "// Source: shared/eve-expressions.json (docs/eveface_design.png).",
        "#pragma once", "#include <stdint.h>", "typedef enum {",
    ]
    lines += [f"    FACE_EX_{e.upper()}," for e in ids]
    lines += ["    FACE_EX_COUNT", "} face_expression_t;"]
    for name, values in (("ids", ids), ("names_zh", [e["name_zh"] for e in expressions])):
        lines += [f"static const char *const k_face_expression_{name}[] = {{"]
        lines += [f"    {json.dumps(v, ensure_ascii=False)}," for v in values]
        lines += ["};"]
    lines += ["static const face_expression_t k_face_preview_expressions[] = {"]
    lines += [f"    FACE_EX_{e.upper()}," for e in order]
    lines += ["};", f"#define FACE_PREVIEW_EXPRESSION_COUNT {len(order)}"]
    lines += ["static const int16_t k_face_eve_shapes[][26] = {"]
    lines += ["    {" + ", ".join(map(str, p)) + "}, // " + name for name, p in shapes.items()]
    lines += ["};", "static const uint8_t k_face_eve_eyes[FACE_EX_COUNT][2] = {"]
    shape_ids = list(shapes)
    lines += [f"    {{{shape_ids.index(e['eyes'][0])}, {shape_ids.index(e['eyes'][1])}}}, // {e['id']}"
              for e in expressions]
    lines += ["};", ""]
    js = "// Generated by tools/generate_face_themes.py; DO NOT EDIT.\n"
    js += "export const EVE = " + json.dumps(data, ensure_ascii=False, indent=2) + ";\n"
    return "\n".join(lines), js


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail if generated header is stale")
    args = parser.parse_args()
    theme_data = json.loads(SOURCE.read_text(encoding="utf-8"))
    expression_data = json.loads(EXPRESSIONS_SOURCE.read_text(encoding="utf-8"))
    expressions, preview = generate_expressions(expression_data)
    rust = "// Generated by tools/generate_face_themes.py; DO NOT EDIT.\n"
    for name, values in (("THEME_IDS", [t["id"] for t in theme_data["themes"]]),
                         ("EXPRESSION_IDS", [e["id"] for e in expression_data["expressions"]])):
        rust += f"pub const {name}: &[&str] = &[\n"
        rust += "".join(f"    {json.dumps(v)},\n" for v in values) + "];\n"
    outputs = {
        TARGET: generate(theme_data),
        EXPRESSIONS_TARGET: expressions,
        PREVIEW_TARGET: preview,
        RUST_TARGET: rust,
        SERVER_TS_TARGET: "// Generated by tools/generate_face_themes.py; DO NOT EDIT.\n"
        + "export const FACE_PREVIEWS = "
        + json.dumps([next({"id": e["id"], "name": e["name_zh"]}
                           for e in expression_data["expressions"] if e["id"] == eid)
                      for eid in expression_data["preview_order"]], ensure_ascii=False, indent=2)
        + " as const;\n",
    }
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Stale {path.relative_to(ROOT)}; run python3 tools/generate_face_themes.py")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print(f"Wrote {path.relative_to(ROOT)}")
    if args.check:
        print("Appearance and EVE manifests match firmware and browser outputs")


if __name__ == "__main__":
    main()
