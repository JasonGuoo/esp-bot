#!/usr/bin/env python3
"""Compile appearance-pack manifests into a small firmware const table."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "shared" / "themes.json"
TARGET = ROOT / "firmware" / "components" / "face" / "include" / "face_themes_generated.h"
FIELDS = ("background", "eye", "pupil", "subtitle_bg", "subtitle_text", "chrome", "chrome_text")
RENDERERS = ("outline", "pill")  # must correspond to compiled face_renderer drivers


def generate(data: dict) -> str:
    themes = data["themes"]
    if data.get("schema_version") != 1 or not themes:
        raise ValueError("Unsupported or empty theme schema")
    seen = set()
    lines = [
        "// Generated by tools/generate_face_themes.py; DO NOT EDIT.",
        "// Appearance manifest: shared/themes.json. Extend with new renderer modules.",
        "#pragma once",
        "#include <stdint.h>",
        "typedef struct {",
        "    const char *id;",
        "    const char *name;",
        "    const char *name_zh;",
        "    const char *renderer_id;",
    ]
    lines += [f"    uint32_t {field};" for field in FIELDS]
    lines += [
        "    uint16_t blink_interval_ms;",
        "    uint16_t blink_duration_ms;",
        "    uint8_t gaze_smoothing;",
        "} face_theme_t;",
        "static const face_theme_t k_face_themes[] = {",
    ]
    for theme in themes:
        tid = theme["id"]
        if not re.fullmatch(r"[a-z][a-z0-9_-]*", tid) or tid in seen:
            raise ValueError(f"Invalid or duplicate theme ID: {tid}")
        seen.add(tid)
        if not re.fullmatch(r"[A-Za-z0-9 -]+", theme["name"]):
            raise ValueError("English name must be ASCII")
        if not isinstance(theme.get("name_zh"), str) or not theme["name_zh"]:
            raise ValueError(f"Missing localized name: {tid}")
        renderer = theme.get("renderer")
        if renderer not in RENDERERS:
            raise ValueError(f"Unregistered renderer: {renderer}")
        colors = []
        for field in FIELDS:
            value = theme[field]
            if not re.fullmatch(r"#[0-9A-Fa-f]{6}", value):
                raise ValueError(f"Invalid hex in {tid}.{field}")
            colors.append("0x" + value[1:].upper())
        motion = theme.get("motion", {})
        if not isinstance(motion, dict):
            raise ValueError(f"Invalid motion object in {tid}")
        blink_interval = motion.get("blink_interval_ms", 3600)
        blink_duration = motion.get("blink_duration_ms", 130)
        easing = motion.get("gaze_smoothing", 4)
        for label, number, low, high in (
            ("blink_interval_ms", blink_interval, 500, 60000),
            ("blink_duration_ms", blink_duration, 70, 2000),
            ("gaze_smoothing", easing, 1, 20),
        ):
            if isinstance(number, bool) or not isinstance(number, int) or not low <= number <= high:
                raise ValueError(f"{tid}.{label} must be integer {low}..{high}")
        strings = ", ".join(json.dumps(theme[key], ensure_ascii=False) for key in (
            "id", "name", "name_zh", "renderer"))
        values = ", ".join(colors + list(map(str, (blink_interval, blink_duration, easing))))
        lines.append(f"    {{{strings}, {values}}},")
    lines += [
        "};",
        "#define FACE_THEME_COUNT (sizeof(k_face_themes) / sizeof(k_face_themes[0]))",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail if generated header is stale")
    args = parser.parse_args()
    content = generate(json.loads(SOURCE.read_text(encoding="utf-8")))
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
            raise SystemExit("Generated header stale; run python3 tools/generate_face_themes.py")
        print("Appearance manifest matches firmware header")
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(content, encoding="utf-8")
        print(f"Wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
